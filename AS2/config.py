def build_info():
    """str: บอกว่ากำลังรันโค้ดจากไฟล์ไหน แก้ล่าสุดเมื่อไร + ค่าสำคัญ - ใช้เช็คว่าที่แก้ไปมีผลจริง"""
    import datetime
    import os
    here = os.path.dirname(os.path.abspath(__file__))
    stamps = []
    for name in ("config.py", "robots.py", "explorer.py", "gui.py"):
        try:
            t = os.path.getmtime(os.path.join(here, name))
            stamps.append(f"{name} {datetime.datetime.fromtimestamp(t):%d/%m %H:%M:%S}")
        except OSError:
            stamps.append(f"{name} ?")
    return (f"[build] โฟลเดอร์: {here}\n"
            f"[build] แก้ล่าสุด: {', '.join(stamps)}\n"
            f"[build] YAW_SIGN={YAW_SIGN} GIMBAL_RIGHT_YAW={GIMBAL_RIGHT_YAW} "
            f"WALL_EXPECT={WALL_EXPECT_MM} THRESH={WALL_THRESHOLD_MM} USE_SHARP={USE_SHARP} "
            f"MOVE_FACTOR={MOVE_FACTOR_FWD}/{MOVE_FACTOR_STRAFE}")
